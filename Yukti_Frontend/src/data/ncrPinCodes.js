export const NCR_SHIPPING_CHARGE = 1000;
export const OUTSIDE_NCR_SHIPPING_ESTIMATE = "Rs. 10,000 to Rs. 30,000";
export const CHECKOUT_PIN_STORAGE_KEY = "checkoutPin";

export function readSavedPinCode() {
  return normalizePinCode(
    sessionStorage.getItem(CHECKOUT_PIN_STORAGE_KEY) ||
      localStorage.getItem(CHECKOUT_PIN_STORAGE_KEY) ||
      ""
  );
}

export function savePinCode(value) {
  const pin = normalizePinCode(value);
  sessionStorage.setItem(CHECKOUT_PIN_STORAGE_KEY, pin);
  localStorage.setItem(CHECKOUT_PIN_STORAGE_KEY, pin);
  return pin;
}

export function getShippingSummary(pinCode) {
  const pin = normalizePinCode(pinCode);
  if (pin.length !== 6) {
    return { status: "pending", pin, shipping: 0, billedSeparately: false };
  }
  if (isNcrPinCode(pin)) {
    return { status: "ncr", pin, shipping: NCR_SHIPPING_CHARGE, billedSeparately: false };
  }
  return { status: "outside", pin, shipping: 0, billedSeparately: true };
}

export function normalizePinCode(value) {
  return String(value || "").replace(/\D/g, "").slice(0, 6);
}

export function isNcrPinCode(value) {
  return NCR_PIN_CODES.has(normalizePinCode(value));
}

export function getShippingCharge(pinCode) {
  return isNcrPinCode(pinCode) ? NCR_SHIPPING_CHARGE : null;
}
